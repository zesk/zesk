__zeskChangeLogGenerate() {
  local handler="$1" && shift
  local prefix="$1"

  local home
  home=$(catchReturn "$handler" buildHome) || return $?
  echo "<!-- GENERATED BY ${BASH_SOURCE[0]} -->"
  echo "<!-- DO NOT EDIT THIS FILE - it will be overwritten upon release -->"
  echo "<!-- Edit ./documentation/source/release/vX.X.X.md instead -->"
  echo
  local releasePath="$home/documentation/source/release"
  catchEnvironment "$handler" cat "$releasePath/header.md" || return $?
  local linksSuffix
  linksSuffix=$(fileTemporaryName "$handler") || return $?
  local clean=("$linksSuffix")
  catchEnvironment "$handler" muzzle pushd "$releasePath" || return $?
  local undo=(muzzle popd)
  local f prevVersion=""
  for f in $(find . -type f -name '*.md' | cut -d / -f 2 | grep -e '^v' | versionSort -r); do
    printf "\n"
    catchEnvironment "$handler" cat "$f" || returnClean $? "${clean[@]}" || returnUndo $? "${undo[@]}" || return $?
    local rawVersion="$f"
    rawVersion=${rawVersion%%.md}
    if [ -n "$prevVersion" ]; then
      catchEnvironment "$handler" printf "[%s]: %s\n" "$rawVersion" "$prefix$prevVersion...$rawVersion" >>"$linksSuffix" || returnClean $? "${clean[@]}" || returnUndo $? "${undo[@]}" || return $?
    fi
    prevVersion="$rawVersion"
  done
  catchEnvironment "$handler" muzzle popd || returnClean $? "${clean[@]}" || return $?
  catchEnvironment "$handler" cat "$releasePath/footer.md" || returnClean $? "${clean[@]}" || return $?
  catchEnvironment "$handler" cat "$linksSuffix" || returnClean $? "${clean[@]}" || return $?
  catchEnvironment "$handler" rm "$linksSuffix" || return $?
}

__zeskChangeLog() {
  local handler="$1" currentVersion="$2"
  local currentVersion currentChangeLog changeLog remoteChangeLogName remoteChangeLog

  export GITHUB_REPOSITORY_OWNER GITHUB_REPOSITORY_NAME
  usageRequireEnvironment "$handler" GITHUB_REPOSITORY_OWNER GITHUB_REPOSITORY_NAME || return $?

  currentChangeLog="$(catchEnvironment "$handler" releaseNotes)" || return $?

  [ -f "$currentChangeLog" ] || throwEnvironment "$handler" "$currentChangeLog is missing" || return $?

  #========================================================================
  #
  #  Generate our release notes for the online release
  #  Update the code in CHANGELOG.md which is effectively a concatenation of files
  #
  start=$(catchReturn "$handler" timingStart) || return $?
  remoteChangeLogName=".release-notes.md"
  remoteChangeLog="./$remoteChangeLogName"
  {
    figlet "zesk $currentVersion" | awk '{ print "    " $0 }'
    echo
    echo "> Released on $releaseDate"
    echo
    cat "$currentChangeLog"
  } >"$remoteChangeLog"

  changeLog=./CHANGELOG.md
  __zeskChangeLogGenerate "$handler" "https://github.com/$GITHUB_REPOSITORY_OWNER/$GITHUB_REPOSITORY_NAME/compare/" >"$changeLog"

  printf "%s\n" "$remoteChangeLog"
}

#
# Push a new tag to GitHub which then triggers a new release to Packagist automatically
#
zeskDeploy() {
  local handler="_${FUNCNAME[0]}"
  local home releaseDate releaseStart start
  local ee=(GITHUB_ACCESS_TOKEN GITHUB_REPOSITORY_OWNER GITHUB_REPOSITORY_NAME)

  export "${ee[@]}"

  whichExists --any figlet toilet || catchReturn "$handler" packageInstall toilet || return $?

  home=$(catchReturn "$handler" buildHome) || return $?
  releaseDate=$(catchEnvironment "$handler" date) || return $?
  releaseStart=$(catchReturn "$handler" timingStart) || return $?

  catchReturn "$handler" buildEnvironmentLoad "${ee[@]}" || return $?

  catchReturn "$handler" environmentFileLoad --optional "$home/.local.env" --require "$home/.env" || return $?

  [ -d "$home/.git" ] || throwEnvironment "$handler" "Missing .git directory" || return $?

  catchEnvironment "$handler" gitInstall || return $?
  catchEnvironment "$handler" phpComposer "$home" || return $?

  local remoteChangeLog currentVersion

  currentVersion=$(catchEnvironment "$handler" hookRun version-current) || return $?

  statusMessage decorate info "Generating release notes and CHANGELOG ... "
  start=$(catchReturn "$handler" timingStart) || return $?
  remoteChangeLog=$(__zeskChangeLog "$handler" "$currentVersion") || return $?
  timingReport "$start" OK

  #========================================================================
  #                _
  #   _______  ___| | __
  #  |_  / _ \/ __| |/ /
  #   / /  __/\__ \   <
  #  /___\___||___/_|\_\
  #
  bigText "zesk $currentVersion"
  local appId
  appId="$(catchReturn "$handler" hookRun application-id)" || return $?
  decorate pair "Application ID" "$appId"

  #========================================================================
  #
  # Send release API call to GitHub to make tagged version a release with
  # release notes.
  #

  statusMessage decorate info "Mark release in GitHub ... "
  usageRequireEnvironment "$handler" GITHUB_ACCESS_TOKEN GITHUB_ACCESS_TOKEN_EXPIRE GITHUB_REPOSITORY_OWNER GITHUB_REPOSITORY_NAME || return $?
  start=$(catchReturn "$handler" timingStart) || return $?
  githubRelease --token "$GITHUB_ACCESS_TOKEN" --owner "$GITHUB_REPOSITORY_OWNER" --name "$GITHUB_REPOSITORY_NAME" --expire "$GITHUB_ACCESS_TOKEN_EXPIRE" "$remoteChangeLog" "$currentVersion" "$appId" || return $?
  printf "%s\n\n" "$(timingReport "$start" OK)"

  #========================================================================
  #
  # I think things change in GitHub when we do a release (maybe?) so sync back to origin here
  #
  decorate info "Pull github and push origin ... " && echo
  decorate decoration "$(echoBar)"
  decorate info "git pull --all" && echo
  start=$(catchReturn "$handler" timingStart) || return $?
  # TODO Remove this if they are AOK
  executeEcho git pull --all || decorate red "Failed: $?"
  printf -- "\n"
  decorate info "git push origin" && echo
  executeEcho git push origin || decorate red "Failed: $?"
  decorate decoration "$(echoBar)"
  printf "%s\n\n" "$(timingReport "$start" OK)"
  #========================================================================
  bigText "zesk $currentVersion OK"
  timingReport "$releaseStart" "Release complete."
}
_zeskDeploy() {
  # __IDENTICAL__ usageDocument 1
  usageDocument "${BASH_SOURCE[0]}" "${FUNCNAME[0]#_}" "$@"
}
